    private void processPayment() {
    model = (DefaultTableModel) jTable1.getModel();
    StringBuilder proId = new StringBuilder();
    StringBuilder proName = new StringBuilder();

    for (int i = 0; i < model.getRowCount(); i++) {
        proId.append(model.getValueAt(i, 1).toString()).append(",");
        proName.append(model.getValueAt(i, 2).toString()).append(",");
    }

    int pid = dao.getPaymentTable() + 1;
    String cName = txtCname.getText().trim();
    double t;

    try {
        t = Double.parseDouble(txtTotal.getText().trim());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Invalid total value", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    Payment payment = new Payment();
    payment.setPid(pid);
    payment.setcName(cName);
    payment.setProId(proId.toString());
    payment.setProName(proName.toString());
    payment.setTotal(t);
    payment.setDate(txtPaymentdate.getText().trim());

    if (check()) {
        if (dao.insertPayment(payment)) {
            JOptionPane.showMessageDialog(this, "Payment Succeeded");

            for (int i = 0; i < model.getRowCount(); i++) {
                int cid = Integer.parseInt(model.getValueAt(i, 0).toString());
                dao.deleteCart(cid);
            }

            int x = JOptionPane.showConfirmDialog(this, "Do you want to print the receipt?", "Print", JOptionPane.YES_NO_OPTION, 0);
            if (x == JOptionPane.YES_OPTION) {
                printReceipt(cName, t);
            } else {
                setVisible(false);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Payment Failed", "Warning", JOptionPane.WARNING_MESSAGE);
        }
    }
}
    
    
    private void printReceipt(String cName, double t) {
    try {
        MessageFormat header = new MessageFormat("***RESTORA*** \nName: " + cName + " \n Total ($): " + t);

        MessageFormat footer = new MessageFormat("Page {0, number, integer}");
        jTable1.print(JTable.PrintMode.FIT_WIDTH, header, footer);
        setVisible(false);
    } catch (PrinterException ex) {
        JOptionPane.showMessageDialog(null, ex.getMessage());
    }
}


    

