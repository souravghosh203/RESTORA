    public void cash() {
        try {
            double cash = Double.parseDouble(txtCash.getText().trim());
            double total = Double.parseDouble(txtTotal.getText().trim());
            double change = (cash - total);

            txtChanges.setText(String.valueOf(change));

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Not enough cash entered", "Warning", 2);
        }
    }

    public boolean check() {
        if (txtCname.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Customer name is required!!!", "Warning", 2);
            return false;
        }
        if (txtCash.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Cash payment is required!!!", "Warning", 2);
            return false;
        }
        double change = Double.parseDouble(txtChanges.getText().trim());
        if (change < 0.0) {

            JOptionPane.showMessageDialog(this, "Not enough cash entered!!!", "Warning", 2);
            return false;
        }
        return true;
    }

